const path = require('path');
const { Pool } = require('pg');
const { createRepository } = require('./lib/repository.cjs');
const { createSQLStore, pgDriver } = require('./lib/sql-store.cjs');
const { createLocalStore } = require('./lib/local-store.cjs');
const pool = process.env.DATABASE_URL ? new Pool({ connectionString: process.env.DATABASE_URL, ...(process.env.PGSSL === 'disable' ? { ssl: false } : { ssl: { rejectUnauthorized: true, ...(process.env.PGSSL_CA ? { ca: process.env.PGSSL_CA } : {}) } }) }) : null;
const store = pool ? createSQLStore(pgDriver(pool)) : createLocalStore(process.env.DATA_DIR || path.join(__dirname, 'data'));
const repository = createRepository(store);
const ready = store.initialize(process.env.INITIAL_ADMIN_PASSWORD);
module.exports = { ...repository, ready, close: async () => { if (pool) await pool.end(); } };
